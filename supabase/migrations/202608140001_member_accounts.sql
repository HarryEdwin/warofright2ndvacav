drop policy if exists "read own profile or admin" on public.profiles;
create policy "read own profile or admin" on public.profiles
    for select to authenticated
    using (id = auth.uid() or public.is_admin());

drop policy if exists "admins update profiles" on public.profiles;
create policy "admins update profiles" on public.profiles
    for update to authenticated
    using (public.is_admin())
    with check (public.is_admin());

drop policy if exists "read own member record or admin" on public.member_records;
create policy "read own member record or admin" on public.member_records
    for select to authenticated
    using ((profile_id = auth.uid() and public.is_approved_member()) or public.is_admin());

drop policy if exists "admins insert member records" on public.member_records;
create policy "admins insert member records" on public.member_records
    for insert to authenticated
    with check (public.is_admin());

drop policy if exists "admins update member records" on public.member_records;
create policy "admins update member records" on public.member_records
    for update to authenticated
    using (public.is_admin())
    with check (public.is_admin());

drop policy if exists "admins delete member records" on public.member_records;
create policy "admins delete member records" on public.member_records
    for delete to authenticated
    using (public.is_admin());

drop policy if exists "admins manage notes" on public.admin_notes;
create policy "admins manage notes" on public.admin_notes
    for all to authenticated
    using (public.is_admin())
    with check (public.is_admin() and created_by = auth.uid());

drop policy if exists "admins read audit logs" on public.audit_logs;
create policy "admins read audit logs" on public.audit_logs
    for select to authenticated
    using (public.is_admin());

revoke all on public.profiles, public.member_records, public.admin_notes, public.audit_logs from anon;
grant select, update on public.profiles to authenticated;
grant select, insert, update, delete on public.member_records to authenticated;
grant select, insert, update, delete on public.admin_notes to authenticated;
grant select on public.audit_logs to authenticated;
grant usage, select on sequence public.admin_notes_id_seq to authenticated;

