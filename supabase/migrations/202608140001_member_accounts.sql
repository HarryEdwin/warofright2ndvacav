create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    new_qq text := new.raw_user_meta_data ->> 'qq_number';
    new_nickname text := btrim(new.raw_user_meta_data ->> 'nickname');
begin
    if new_qq is null or new_qq !~ '^[0-9]{5,12}$' then
        raise exception 'Invalid QQ number';
    end if;
    if new_nickname is null or char_length(new_nickname) not between 2 and 24 then
        raise exception 'Invalid nickname';
    end if;

    insert into public.profiles (id, qq_number, nickname)
    values (new.id, new_qq, new_nickname);
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

create or replace function public.protect_profile_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.id <> old.id or new.qq_number <> old.qq_number or new.created_at <> old.created_at then
        raise exception 'Identity fields cannot be changed';
    end if;

    if new.role <> old.role and auth.uid() is not null and not public.is_super_admin() then
        raise exception 'Only a super administrator can change roles';
    end if;

    if old.role in ('admin', 'super_admin')
       and auth.uid() is not null
       and auth.uid() <> old.id
       and not public.is_super_admin() then
        raise exception 'Only a super administrator can modify another administrator';
    end if;

    if new.account_status <> old.account_status then
        if auth.uid() is not null and not public.is_admin() then
            raise exception 'Only an administrator can change account status';
        end if;
        if new.account_status = 'approved' then
            new.approved_at := now();
            new.approved_by := auth.uid();
        else
            new.approved_at := null;
            new.approved_by := null;
        end if;
    end if;

    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists protect_profile_update on public.profiles;
create trigger protect_profile_update
    before update on public.profiles
    for each row execute function public.protect_profile_update();

create or replace function public.touch_member_record()
returns trigger
language plpgsql
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists touch_member_record on public.member_records;
