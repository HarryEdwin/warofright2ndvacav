create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    qq_number text not null unique check (qq_number ~ '^[0-9]{5,12}$'),
    nickname text not null check (char_length(nickname) between 2 and 24),
    account_status text not null default 'pending'
        check (account_status in ('pending', 'approved', 'rejected', 'suspended')),
    role text not null default 'member'
        check (role in ('member', 'admin', 'super_admin')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    approved_at timestamptz,
    approved_by uuid references public.profiles(id) on delete set null
);

create unique index if not exists profiles_nickname_unique_ci
    on public.profiles (lower(btrim(nickname)));

create table if not exists public.member_records (
    profile_id uuid primary key references public.profiles(id) on delete cascade,
    company text not null default '',
    current_rank text not null default '',
    promotion_path text not null default '',
    joined_on date,
    member_status text not null default '现役',
    attendance_count integer not null default 0 check (attendance_count >= 0),
    activity_total integer not null default 0 check (activity_total >= 0),
    experience_points integer not null default 0 check (experience_points >= 0),
    training_points integer not null default 0 check (training_points >= 0),
    command_points integer not null default 0 check (command_points >= 0),
    service_points integer not null default 0 check (service_points >= 0),
    achievements text[] not null default '{}',
    updated_at timestamptz not null default now(),
    constraint attendance_not_above_total check (attendance_count <= activity_total)
);

create table if not exists public.admin_notes (
    id bigint generated by default as identity primary key,
    profile_id uuid not null references public.profiles(id) on delete cascade,
    note text not null check (char_length(note) between 1 and 2000),
    created_by uuid not null references public.profiles(id) on delete restrict,
    created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
    id bigint generated by default as identity primary key,
    actor_id uuid references public.profiles(id) on delete set null,
    target_id uuid references public.profiles(id) on delete set null,
    action text not null,
    before_data jsonb,
    after_data jsonb,
    created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.profiles
        where id = auth.uid()
          and account_status = 'approved'
          and role in ('admin', 'super_admin')
    );
$$;

