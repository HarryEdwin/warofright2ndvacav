create or replace function public.audit_profile_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.audit_logs (actor_id, target_id, action, before_data, after_data)
    values (auth.uid(), new.id, 'profile.updated', to_jsonb(old), to_jsonb(new));
    return new;
end;
$$;

drop trigger if exists audit_profile_change on public.profiles;
create trigger audit_profile_change
    after update on public.profiles
    for each row execute function public.audit_profile_change();

-- Approving a member also confirms the synthetic QQ login identity. This keeps
-- pending applicants unable to sign in even when email confirmation is enabled.
create or replace function public.confirm_approved_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
    if new.account_status = 'approved' and old.account_status <> 'approved' then
        update auth.users
        set email_confirmed_at = coalesce(email_confirmed_at, now()),
            updated_at = now()
        where id = new.id;
    end if;
    return new;
end;
$$;

drop trigger if exists confirm_approved_user on public.profiles;
create trigger confirm_approved_user
    after update of account_status on public.profiles
    for each row execute function public.confirm_approved_user();

create or replace function public.audit_member_record_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.audit_logs (actor_id, target_id, action, before_data, after_data)
    values (
        auth.uid(),
        coalesce(new.profile_id, old.profile_id),
        case when tg_op = 'INSERT' then 'member_record.created' else 'member_record.updated' end,
        case when tg_op = 'INSERT' then null else to_jsonb(old) end,
        to_jsonb(new)
    );
    return new;
end;
$$;

drop trigger if exists audit_member_record_change on public.member_records;
create trigger audit_member_record_change
    after insert or update on public.member_records
    for each row execute function public.audit_member_record_change();

